// Generates supabase/seed.sql from the current src/data files.
// Run:  npm run seed:generate
import { readFileSync, writeFileSync } from "node:fs";
import { profileBundle } from "../src/data/profile.ts";
import { projects } from "../src/data/projects.ts";
import { collabs, reels } from "../src/data/collabs.ts";
import { mediakit } from "../src/data/mediakit.ts";

const q = (s) => `'${String(s ?? "").replace(/'/g, "''")}'`;
const json = (o) => `$json$${JSON.stringify(o)}$json$::jsonb`;
const arr = (a) => `array[${a.map(q).join(",")}]::text[]`;

const out = [];
out.push("-- Generated by scripts/make-seed.mjs from src/data. Run after schema.sql.");
out.push("begin;");
out.push(
  `insert into public.site_profile (id, data) values (1, ${json(profileBundle)}) on conflict (id) do update set data = excluded.data, updated_at = now();`
);
out.push(`insert into public.mediakit_snapshots (period, data) values (${q(mediakit.period)}, ${json(mediakit)});`);
projects.forEach((p, i) => {
  out.push(
    `insert into public.projects (slug, title, kind, category, image_url, live_url, summary, stack, featured, status, published, sort) values (${q(p.id)}, ${q(p.title)}, ${q(p.kind)}, ${q(p.category)}, ${q(p.image)}, ${q(p.url)}, ${q(p.summary)}, ${arr(p.stack)}, ${p.featured ? "true" : "false"}, ${q(p.status ?? "live")}, true, ${i}) on conflict (slug) do nothing;`
  );
});
out.push(
  "insert into public.project_private (project_id, stage, payment_status) select id, case when status = 'in-progress' then 'development' else 'delivered' end, 'na' from public.projects on conflict (project_id) do nothing;"
);
collabs.forEach((c, i) =>
  out.push(`insert into public.collabs (name, category, sort) values (${q(c.name)}, ${q(c.category)}, ${i});`)
);
reels.forEach((r, i) =>
  out.push(
    `insert into public.reels (code, category, partner, note, thumb_url, sort) values (${q(r.id)}, ${q(r.category)}, ${q(r.partner)}, ${q(r.note ?? "")}, ${q(`/images/reels/${r.id}.jpg`)}, ${i}) on conflict (code) do nothing;`
  )
);
out.push("commit;");
const seed = out.join("\n") + "\n";
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), seed);

// setup.sql = schema + seed + make-admin, so first-time setup is one paste.
const schema = readFileSync(new URL("../supabase/schema.sql", import.meta.url), "utf8");
const admin = readFileSync(new URL("../supabase/make-admin.sql", import.meta.url), "utf8");
writeFileSync(
  new URL("../supabase/setup.sql", import.meta.url),
  [
    "-- ONE-TIME SETUP: create your login first (Authentication → Users → Add user),",
    "-- then paste this whole file into SQL Editor → New query → Run.",
    "",
    schema,
    seed,
    admin,
  ].join("\n")
);
console.log(`seed.sql + setup.sql: ${projects.length} projects, ${collabs.length} collabs, ${reels.length} reels, profile + media kit`);
